describe('encodeQr', () => {
	for (const testCase of CASES) {
		// Only a module-for-module match proves a scanner can read it: a plausible-looking
		// matrix with, say, misplaced alignment patterns decodes as nothing at all.
		it(`matches the reference symbol for ${testCase.name}`, () => {
			const matrix = encodeQr(testCase.text)
			const size = testCase.version * 4 + 17
			expect(matrix).toHaveLength(size)
			expect(matrix.map((row) => row.map((dark) => (dark ? '1' : '0')).join(''))).toEqual(testCase.rows)
		})
	}

	it('rejects a payload no version can hold', () => {
		expect(() => encodeQr('a'.repeat(3000))).toThrow()
	})
})
